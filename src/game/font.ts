const cache = new Map<string, HTMLCanvasElement>();

function glyphCanvas(ch: string, color: string, outline: string | null): HTMLCanvasElement {
  const key = `${ch}|${color}|${outline ?? ""}`;
  let c = cache.get(key);
  if (c) return c;
  const rows = GLYPHS[ch] ?? GLYPHS["?"];
  c = document.createElement("canvas");
  c.width = 7;
  c.height = 9;
  const g = c.getContext("2d")!;
  if (outline) {
    g.fillStyle = outline;
    for (let y = 0; y < 7; y++)
      for (let x = 0; x < 5; x++)
        if (rows[y][x] === "#")
          for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) g.fillRect(x + 1 + dx, y + 1 + dy, 1, 1);
  }
  g.fillStyle = color;
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (rows[y][x] === "#") g.fillRect(x + 1, y + 1, 1, 1);
  cache.set(key, c);
  return c;
}

export type Align = "left" | "center" | "right";

export function textWidth(str: string, scale = 1): number {
  return str.length * 6 * scale - scale;
}

/** Draw pixel text. Letters are uppercased; unknown characters render as '?'. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  color = "#fff",
  opts: { scale?: number; align?: Align; outline?: string | null } = {},
) {
  const scale = opts.scale ?? 1;
  const outline = opts.outline === undefined ? "#000" : opts.outline;
  const s = str.toUpperCase();
  const w = textWidth(s, scale);
  let cx = x;
  if (opts.align === "center") cx = Math.round(x - w / 2);
  else if (opts.align === "right") cx = Math.round(x - w);
  const prev = ctx.imageSmoothingEnabled;
  ctx.imageSmoothingEnabled = false;
  for (const ch of s) {
    const g = glyphCanvas(ch, color, outline);
    ctx.drawImage(g, cx - scale, y - scale, 7 * scale, 9 * scale);
    cx += 6 * scale;
  }
  ctx.imageSmoothingEnabled = prev;
}
